#pragma once
// ============================================================================
// 三角形上的对称求积规则
// ----------------------------------------------------------------------------
//   点用重心坐标 (l0, l1, l2) 给出, l0+l1+l2 = 1;
//   权重视一化到 sum(w) = 1, 于是
//        ∫_T f dA  ≈  area(T) * Σ_q w_q f(l_q)
//   这样调用方只要乘单元面积, 不必再记参考三角形面积是 1/2。
//
//   选规则的准则: 刚度矩阵被积函数是 ∇N·∇N, 次数 2*(order-1);
//   质量矩阵是 N·N, 次数 2*order; 载荷项是 f*N, f 非多项式时还要留出余量。
//   assembler 里默认按这个准则取, 见各函数的 qdeg 默认值。
// ============================================================================
#include <cstddef>
#include <stdexcept>
#include <vector>

namespace fem
{

struct TriQuad
{
    int                  degree = 1;      // 代数精度
    std::vector<double>  l0, l1, l2, w;   // 重心坐标与权重

    std::size_t size() const { return w.size(); }
};

inline TriQuad tri_quadrature(int want_degree)
{
    // 1 点, 精度 1 (形心)
    static const double p1[] = {
        1.0 / 3.0, 1.0 / 3.0, 1.0 / 3.0, 1.0
    };
    // 3 点, 精度 2
    static const double p2[] = {
        2.0 / 3.0, 1.0 / 6.0, 1.0 / 6.0, 1.0 / 3.0,
        1.0 / 6.0, 2.0 / 3.0, 1.0 / 6.0, 1.0 / 3.0,
        1.0 / 6.0, 1.0 / 6.0, 2.0 / 3.0, 1.0 / 3.0
    };
    // 6 点, 精度 4
    static const double p4[] = {
        0.816847572980459, 0.091576213509771, 0.091576213509771, 0.109951743655322,
        0.091576213509771, 0.816847572980459, 0.091576213509771, 0.109951743655322,
        0.091576213509771, 0.091576213509771, 0.816847572980459, 0.109951743655322,
        0.108103018168070, 0.445948490915965, 0.445948490915965, 0.223381589678011,
        0.445948490915965, 0.108103018168070, 0.445948490915965, 0.223381589678011,
        0.445948490915965, 0.445948490915965, 0.108103018168070, 0.223381589678011
    };
    // 7 点, 精度 5 (形心 + 两个三点轨道)
    static const double p5[] = {
        1.0 / 3.0,              1.0 / 3.0,              1.0 / 3.0,              0.225,
        0.470142064105115,      0.470142064105115,      0.059715871789770,      0.1323941527,
        0.470142064105115,      0.059715871789770,      0.470142064105115,      0.1323941527,
        0.059715871789770,      0.470142064105115,      0.470142064105115,      0.1323941527,
        0.101286507323456,      0.101286507323456,      0.797426985353087,      0.1259391805,
        0.101286507323456,      0.797426985353087,      0.101286507323456,      0.1259391805,
        0.797426985353087,      0.101286507323456,      0.101286507323456,      0.1259391805
    };

    TriQuad q;
    const double* src = nullptr;
    std::size_t   np  = 0;

    if      (want_degree <= 1) { q.degree = 1; src = p1; np = 1; }
    else if (want_degree <= 2) { q.degree = 2; src = p2; np = 3; }
    else if (want_degree <= 4) { q.degree = 4; src = p4; np = 6; }
    else if (want_degree <= 5) { q.degree = 5; src = p5; np = 7; }
    else throw std::invalid_argument("tri_quadrature: 只支持代数精度 <= 5");

    q.l0.resize(np); q.l1.resize(np); q.l2.resize(np); q.w.resize(np);
    for (std::size_t i = 0; i < np; ++i)
    {
        q.l0[i] = src[4 * i + 0];
        q.l1[i] = src[4 * i + 1];
        q.l2[i] = src[4 * i + 2];
        q.w[i]  = src[4 * i + 3];
    }
    return q;
}

}   // namespace fem
